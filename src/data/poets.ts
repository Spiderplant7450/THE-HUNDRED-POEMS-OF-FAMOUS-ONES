// Provide quick lookup map by author name or normalized slug
export const POET_BY_NAME: Record<string, PoetInfo> = {};
POETS.forEach((poet) => {
  POET_BY_NAME[poet.name.toLowerCase()] = poet;
  POET_BY_NAME[poet.id] = poet;
});

// Normalized matching helper
export function getPoetByName(name: string): PoetInfo | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();
  
  if (POET_BY_NAME[clean]) return POET_BY_NAME[clean];
  
  // Try partial matching
  return POETS.find(
    (p) =>
      clean.includes(p.name.toLowerCase()) ||
      p.name.toLowerCase().includes(clean) ||
      clean.includes(p.id)
  );
}
